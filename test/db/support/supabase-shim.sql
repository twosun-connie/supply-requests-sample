-- Supabase 가 프로젝트에 미리 만들어 두는 것 가운데 마이그레이션이 기대는 부분만 흉내 낸다.
-- 테스트 전용이다. 실제 Supabase 가 아니다. 마이그레이션을 통과시키려고 이 파일을 고치지 않는다.
-- 기본 권한(alter default privileges)은 일부러 흉내 내지 않는다. 마이그레이션이 grant 를 빠뜨리면 테스트가 잡아야 한다.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
create role supabase_auth_admin nologin;

create schema auth;
create table auth.users (
  id                  uuid primary key default gen_random_uuid(),
  email               text unique,
  raw_app_meta_data   jsonb not null default '{}',
  raw_user_meta_data  jsonb not null default '{}',
  created_at          timestamptz not null default now()
);

create function auth.jwt() returns jsonb language sql stable
  as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable
  as $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;
create function auth.role() returns text language sql stable
  as $$ select auth.jwt() ->> 'role' $$;

grant usage on schema auth to anon, authenticated, service_role;
grant execute on all functions in schema auth to anon, authenticated, service_role;
grant usage on schema public to anon, authenticated, service_role;

